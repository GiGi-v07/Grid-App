def _dispatch_ai_worker(ip, base_script_path, data_path, l_rate, job_label, upload_fn, format_bytes_fn, results_dict, results_lock):
    """
    Uploads the customized AI training script and dataset (full or partition)
    to a single worker node using GridApp's upload_file_in_chunks and executes
    it via the worker's standard execute_job RPC.
    """
    scriptdir = os.path.dirname(os.path.abspath(base_script_path))
    temp_dir = os.path.join(scriptdir, "Temp_Jobs")
    os.makedirs(temp_dir, exist_ok=True)
    uid = uuid.uuid4().hex[:8]
    job_id = f"job_{uid}"
    remote_job_file = f"temp_job_{uid}.py"
    remote_data_file = f"temp_data_{uid}.txt"
    local_temp_script = os.path.join(temp_dir, f"_local_prep_{uid}.py")

    try:
        # Prepare worker-specific copy of the AI script with its learning rate & data file
        _build_worker_script(base_script_path, remote_data_file, l_rate, local_temp_script)

        worker = Client.ServerProxy(f"http://{ip}:8000", allow_none=True)
        print(f"Uploading AI script and dataset to {ip}...", flush=True)

        # Upload script and dataset using GridApp's chunk uploader
        upload_fn(worker, local_temp_script, remote_job_file, job_id=job_id, job_name=job_label)
        upload_fn(worker, data_path, remote_data_file, job_id=job_id, job_name=job_label)

        # Execute the training script on the worker via generic execute_job
        t_call = time.time()
        try:
            raw_response = worker.execute_job(remote_job_file, job_id)
        except Exception as e:
            if "takes" in str(e) and "positional arguments" in str(e):
                raw_response = worker.execute_job(remote_job_file)
            else:
                raise
        rt = time.time() - t_call

        print(f"[TRANSFER IN ] Received response from {ip} | Size: {format_bytes_fn(len(raw_response))} | Round-Trip: {rt:.2f}s", flush=True)

        clean_log, model_info = _extract_model_result(raw_response)
        print(f"\n--- Worker Output from {ip} (lr={l_rate}) ---\n{clean_log}", flush=True)

        with results_lock:
            results_dict[ip] = {
                "success": model_info is not None,
                "model": model_info,
                "log": clean_log,
                "learning_rate": l_rate,
            }
    except Exception as e:
        print(f"Error with worker {ip}: {e}", flush=True)
        with results_lock:
            results_dict[ip] = {
                "success": False,
                "model": None,
                "error": str(e),
                "learning_rate": l_rate,
            }
    finally:
        if os.path.exists(local_temp_script):
            try:
                os.remove(local_temp_script)
            except OSError:
                pass


