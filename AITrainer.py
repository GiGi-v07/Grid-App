def consult_council(x1, x2, verbose=False):
    """
    Consults every AI model in the Council simultaneously for inputs (x1, x2).
    Returns the consensus prediction (weighted average across council members)
    and individual member predictions.
    """
    x1, x2 = float(x1), float(x2)
    member_predictions = []
    weighted_sum = 0.0
    total_weight = 0.0

    for idx, member in enumerate(COUNCIL_MODELS, start=1):
        pred = (member["w1"] * x1) + (member["w2"] * x2) + member["bias"]
        weight = max(0.01, float(member.get("weight", 1.0)))
        weighted_sum += pred * weight
        total_weight += weight
        member_predictions.append((member["worker_ip"], pred))
        if verbose:
            print(f"  [Council Member #{{idx}} ({{member['worker_ip']}})] -> Votes: {{pred:7.3f}} "
                  f"(w1={{member['w1']:.3f}}, w2={{member['w2']:.3f}}, b={{member['bias']:.3f}})")

    consensus = weighted_sum / total_weight if total_weight > 0 else 0.0
    return consensus, member_predictions


