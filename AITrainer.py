def _build_worker_script(base_script_path, remote_data_filename, learning_rate, local_temp_path):
    """
    Creates a temporary copy of the AI training script tailored for a specific
    worker node by injecting its assigned dataset filename and learning rate.
    This allows the worker to execute it via standard `execute_job` without
    requiring any AI-specific RPC functions in GridApp.py.
    """
    with open(base_script_path, "r", encoding="utf-8") as f:
        code = f.read()

    # Override default parameters at the top of the worker's script copy
    overrides = (
        f'\n# --- Worker-Specific Overrides Injected by AITrainer ---\n'
        f'DEFAULT_DATA_FILE = {repr(remote_data_filename)}\n'
        f'DEFAULT_LEARNING_RATE = {float(learning_rate)}\n'
        f'SAVE_LOCAL_ARTIFACTS = False\n'
    )

    if "if __name__ ==" in code:
        parts = code.rsplit("if __name__ ==", 1)
        modified_code = parts[0] + overrides + "\nif __name__ ==" + parts[1]
    else:
        modified_code = code + overrides

    with open(local_temp_path, "w", encoding="utf-8") as f:
        f.write(modified_code)


def _extract_model_result(worker_output):
    """
    Parses the worker's stdout response to extract the structured JSON payload
    (prefixed with 'MODEL_RESULT_JSON:') and returns (clean_log, model_dict).
    """
    marker = "MODEL_RESULT_JSON:"
    clean_lines = []
    model_data = None

    for line in worker_output.splitlines():
        if line.strip().startswith(marker):
            raw_json = line.strip()[len(marker):]
            try:
                model_data = json.loads(raw_json)
            except Exception:
                pass
        else:
            clean_lines.append(line)

    return "\n".join(clean_lines), model_data


def _sanitize_name(value):
    """Converts an IP or float string into a safe filename token."""
    return str(value).replace(".", "_").replace(":", "_").replace("-", "neg")


