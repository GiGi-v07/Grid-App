def data_splitting(wkr_ips, scriptpath, datapath, upload_fn, format_bytes_fn, wkr_specs=None):
    """
    Mode 2 - Data Splitting (Council of AIs):
    1. Splits the training dataset across connected workers proportionally to
       each worker's hardware spec_score (CPU cores, free RAM, CPU throughput)
       fetched during the Node Spec Handshake.
    2. Trains a separate model on each worker using its proportional data slice.
    3. Collects all trained models from the workers and combines them into a
       single Council of AIs ensemble.
    4. Evaluates the Council of AIs on testing data and saves both
       'council_weights.json' and a standalone runnable 'council_model.py'.
    """
    print("\n" + "=" * 66)
    print("   MODE 2: DATA SPLITTING (Spec-Proportional -> Council of AIs)")
    print("=" * 66)

    worker_list = list(wkr_ips)
    num_workers = len(worker_list)
    wkr_specs = wkr_specs or {}

    lr_input = input("Enter learning rate for Council workers (default 0.01): ").strip()
    try:
        l_rate = float(lr_input) if lr_input else 0.01
    except ValueError:
        print(f"Invalid learning rate '{lr_input}', defaulting to 0.01.")
        l_rate = 0.01

    # Read valid dataset lines (excluding comments and empty lines)
    with open(datapath, "r", encoding="utf-8") as f:
        valid_lines = [line.strip() for line in f if line.strip() and not line.strip().startswith("#")]

    if len(valid_lines) < num_workers:
        print(f"Error: Dataset has only {len(valid_lines)} rows, cannot split across {num_workers} workers.")
        return

    scriptdir = os.path.dirname(os.path.abspath(scriptpath))
    test_file = os.path.join(scriptdir, "ai_test_data.txt")
    test_x, test_y = load_data(test_file)

    # If no dedicated test file exists, reserve 20% for testing and split the remaining 80%
    if len(test_y) > 0 and os.path.abspath(datapath) != os.path.abspath(test_file):
        train_lines = valid_lines
    else:
        split_idx = max(num_workers, int(len(valid_lines) * 0.8))
        train_lines = valid_lines[:split_idx]
        all_x, all_y = load_data(datapath)
        test_x, test_y = all_x[split_idx:], all_y[split_idx:]

    # Compute each worker's hardware spec_score for proportional data splitting
    total_rows = len(train_lines)
    scores = {}
    for ip in worker_list:
        sp_info = wkr_specs.get(ip, {})
        scores[ip] = max(1.0, float(sp_info.get("spec_score", 10.0)))
    total_spec_score = sum(scores.values())

    temp_partition_files = []
    results = {}
    results_lock = thread.Lock()
    threads = []

    print(f"\nSplitting {total_rows} training records proportionally to Worker Specs across {num_workers} worker(s):")

    try:
        current_idx = 0
        for idx, ip in enumerate(worker_list):
            sp_info = wkr_specs.get(ip, {})
            share_ratio = scores[ip] / total_spec_score
            share_pct = share_ratio * 100.0

            if idx == num_workers - 1:
                end_i = total_rows
            else:
                remaining_workers = num_workers - 1 - idx
                allocated = max(1, round(total_rows * share_ratio))
                max_allowed = total_rows - current_idx - remaining_workers
                end_i = current_idx + min(allocated, max_allowed)

            subset_lines = train_lines[current_idx:end_i]
            temp_dir = os.path.join(scriptdir, "Temp_Jobs")
            os.makedirs(temp_dir, exist_ok=True)
            part_path = os.path.join(temp_dir, f"_partition_{idx + 1}_{uuid.uuid4().hex[:6]}.txt")
            with open(part_path, "w", encoding="utf-8") as pf:
                pf.write("\n".join(subset_lines) + "\n")
            temp_partition_files.append(part_path)

            cores_desc = f"{sp_info.get('cores', '?')} Cores, {sp_info.get('avail_ram_gb', '?')} GB free RAM" if sp_info else "Default Spec"
            print(
                f"  -> Worker {ip} [{cores_desc} | Score: {scores[ip]:.1f} ({share_pct:.1f}%)] : "
                f"Rows {current_idx + 1}..{end_i} ({len(subset_lines)} rows)"
            )
            current_idx = end_i
            job_label = f"AI Council Part {idx + 1}/{num_workers} ({share_pct:.0f}% slice, lr={l_rate})"

            t = thread.Thread(
                target=_dispatch_ai_worker,
                args=(ip, scriptpath, part_path, l_rate, job_label, upload_fn, format_bytes_fn, results, results_lock),
            )
            threads.append(t)
            t.start()

        for t in threads:
            t.join()
    finally:
        # Clean up temporary local partition files on the Master
        for part_path in temp_partition_files:
            if os.path.exists(part_path):
                try:
                    os.remove(part_path)
                except OSError:
                    pass

    # Assemble the Council of AIs from all successful worker models
    council_members = []
    for ip in worker_list:
        res = results.get(ip)
        if res and res.get("success") and res.get("model") and not res["model"].get("diverged"):
            m = res["model"]
            # Weight each council member by its proportional sample share and test R^2 accuracy
            sample_share = max(1, int(m.get("train_samples", 1))) / max(1, total_rows)
            r2_factor = max(0.1, float(m.get("test_r2", 0.5)))
            combined_weight = round(sample_share * r2_factor, 4)
            council_members.append({
                "worker_ip": ip,
                "spec_score": scores.get(ip, 10.0),
                "w1": m["w1"],
                "w2": m["w2"],
                "bias": m["bias"],
                "train_samples": m["train_samples"],
                "worker_test_mse": m["test_mse"],
                "worker_test_r2": m["test_r2"],
                "weight": max(0.01, combined_weight),
            })

    if not council_members:
        print("\nError: No valid worker models were returned to form the Council of AIs.")
        return

    # Compute the combined Council consensus parameters (weighted average of council models)
    total_w = sum(m["weight"] for m in council_members)
    avg_w1 = sum(m["w1"] * m["weight"] for m in council_members) / total_w
    avg_w2 = sum(m["w2"] * m["weight"] for m in council_members) / total_w
    avg_bias = sum(m["bias"] * m["weight"] for m in council_members) / total_w

    # Evaluate the combined Council of AIs on the testing set
    council_eval = evaluate_model(test_x, test_y, avg_w1, avg_w2, avg_bias)
    council_r2_pct = max(0.0, council_eval["r2_score"] * 100.0)

    print("\n" + "=" * 66)
    print("               COUNCIL OF AIs - ENSEMBLE RESULTS")
    print("=" * 66)
    print(f"Council Size (Active Models) : {len(council_members)} Worker(s)")
    for idx, member in enumerate(council_members, start=1):
        m_r2 = max(0.0, member["worker_test_r2"] * 100.0)
        print(f"  Member #{idx} ({member['worker_ip']}) : "
              f"y = {member['w1']:.4f}*x1 + ({member['w2']:.4f})*x2 + {member['bias']:.4f} "
              f"| Slice MSE: {member['worker_test_mse']:.4f} (R^2: {m_r2:.2f}%)")

    print("-" * 66)
    print(f"Council Consensus Equation   : y = {avg_w1:.4f}*x1 + ({avg_w2:.4f})*x2 + {avg_bias:.4f}")
    print(f"Council Test Set MSE         : {council_eval['mse']:.4f}")
    print(f"Council Test Set MAE         : {council_eval['mae']:.4f}")
    print(f"Council Test R^2 Accuracy    : {council_r2_pct:.2f}%")

    # Show live Council consultation on sample test points
    if council_eval["samples"]:
        print("\n--- Live Council Consultation on Test Data ---")
        for s in council_eval["samples"][:3]:
            x1_val, x2_val, actual_val = s["x1"], s["x2"], s["actual"]
            votes_str = ", ".join(
                f"{m['worker_ip']}: {(m['w1']*x1_val + m['w2']*x2_val + m['bias']):.2f}"
                for m in council_members
            )
            print(f"  Input ({x1_val:5.2f}, {x2_val:5.2f}) | Member Votes: [{votes_str}] "
                  f"-> Council Consensus: {s['predicted']:6.3f} (Actual: {actual_val:6.3f})")

    # Save JSON file of the Council weights and individual member models inside Trained_Models/
    models_dir = os.path.join(scriptdir, "Trained_Models")
    os.makedirs(models_dir, exist_ok=True)

    council_json_payload = {
        "council_size": len(council_members),
        "learning_rate": l_rate,
        "consensus_weights": {
            "w1": round(avg_w1, 6),
            "w2": round(avg_w2, 6),
            "bias": round(avg_bias, 6),
        },
        "council_test_mse": round(council_eval["mse"], 6),
        "council_test_mae": round(council_eval["mae"], 6),
        "council_test_r2": round(council_eval["r2_score"], 6),
        "members": council_members,
    }
    council_json_path = os.path.join(models_dir, "council_weights.json")
    with open(council_json_path, "w", encoding="utf-8") as cjf:
        json.dump(council_json_payload, cjf, indent=4)

    # Save standalone runnable Python script for the Council of AIs inside Trained_Models/
    council_py_path = os.path.join(models_dir, "council_model.py")
    ensemble_metrics = {
        "avg_w1": avg_w1,
        "avg_w2": avg_w2,
        "avg_bias": avg_bias,
        "mse": council_eval["mse"],
        "mae": council_eval["mae"],
        "r2_score": council_eval["r2_score"],
    }
    generate_council_script(council_py_path, council_members, ensemble_metrics, council_eval["samples"])

    print("\n[Saved] Council JSON Weights    : Trained_Models/council_weights.json")
    print("[Saved] Council Runnable Script : Trained_Models/council_model.py")
    print("=" * 66)


